// Writes docs/GUIDE-SCREENSHOTS.md (every screenshot to take) and docs/GUIDE-VALUES.md (every private key) from the guide content.
// Run: yarn guide:docs
import { writeFileSync } from "node:fs";
import { TOPICS, SECRET_KEYS } from "../apps/generator/src/guide-content.ts";

const rows = [];
for (const t of TOPICS) {
  t.steps.forEach((s, i) => {
    if (s.shot) rows.push(`| ${t.title} | ${i + 1}. ${s.title} | ${s.shot.caption} | \`apps/generator/public/guide/${s.shot.id}.webp\` | ${s.shot.ratio ?? "16:9"} |`);
  });
}
writeFileSync(
  new URL("../docs/GUIDE-SCREENSHOTS.md", import.meta.url),
  `# Guide: screenshots to take

Generated by \`yarn guide:docs\` from \`apps/generator/src/guide-content.ts\`. Do not edit by hand.

Save each picture as **WebP**, about **1200 px wide**, under **150 KB**, with the file name in the table, into \`apps/generator/public/guide/\`. The page shows it instead of the placeholder as soon as the file exists. Blur or crop names, phone numbers, passwords and anything private.

${rows.length} screenshots:

| Topic | Step | What to capture | File | Ratio |
|---|---|---|---|---|
${rows.join("\n")}
`,
);

const people = SECRET_KEYS.map((k) => `- \`${k}\``).join("\n");
writeFileSync(
  new URL("../docs/GUIDE-VALUES.md", import.meta.url),
  `# Guide: private values

Generated by \`yarn guide:docs\`. Do not edit by hand. **Never write the real values into the repository** (it is public).

The guide text has ${SECRET_KEYS.length} placeholders \`[[key]]\`. The real values (names, phone numbers, e-mail addresses, passwords, Wi-Fi, contract links, amounts) belong in the private backend table \`guide_values\` (Cloudflare D1). The Worker serves them only after Microsoft login exists (\`AUTH_MODE\` is not \`open\`); until then the site shows grey "after sign-in" chips.

Keys:

${people}
`,
);
console.log(`screenshots: ${rows.length}, private keys: ${SECRET_KEYS.length}`);
